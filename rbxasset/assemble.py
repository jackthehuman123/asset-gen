"""Generate the Luau script that assembles an uploaded asset in Roblox Studio.

The Blender -> Studio axis mapping lives ONLY in to_studio (Task 1 may correct it).
"""
from typing import Dict, List

MAP_PROPS = [("color", "ColorMap"), ("normal", "NormalMap"),
             ("roughness", "RoughnessMap"), ("metalness", "MetalnessMap")]
DECAL_THICKNESS = 0.05
STUDS_PER_UNIT = 1.0  # Blender unit -> studs; Task 1 corrects the scale here


def to_studio(v: List[float]) -> List[float]:
    """Blender (x, y, z; z up) -> Studio (x, z, -y)."""
    return [v[0] * STUDS_PER_UNIT, v[2] * STUDS_PER_UNIT, -v[1] * STUDS_PER_UNIT]


def _s(text: str) -> str:
    """Quote a string as a safe Luau double-quoted literal."""
    out = ['"']
    for ch in str(text):
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append("\\%d" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _n(x: float) -> str:
    return repr(round(float(x), 6))


def _vec(v: List[float]) -> str:
    return "Vector3.new(%s, %s, %s)" % (_n(v[0]), _n(v[1]), _n(v[2]))


def generate_luau(manifest: Dict, ids: Dict[str, str], asset_name: str) -> str:
    fbx = manifest.get("fbx")
    model_id = ids[fbx] if fbx in ids else next(
        (i for p, i in ids.items() if p.endswith(".fbx")), None)
    if model_id is None:
        raise ValueError("no model asset id in ids")

    if not manifest.get("meshes"):
        raise ValueError("manifest has no meshes")
    mesh_lines = []
    for m in manifest["meshes"]:
        required = ["color", "normal", "roughness"] + (["metalness"] if m.get("metal") else [])
        for kind in required:
            if kind not in m.get("maps", {}) or m["maps"][kind] not in ids:
                raise ValueError("mesh %s is missing its %s map id" % (m["name"], kind))
        maps = ["%s = %s" % (k, _s(ids[m["maps"][k]]))
                for k, _ in MAP_PROPS if k in m["maps"] and m["maps"][k] in ids]
        mesh_lines.append("\t{ name = %s, collide = %s, %s }" % (
            _s(m["name"]), "true" if m["collide"] else "false", ", ".join(maps)))

    decal_lines = []
    for d in manifest.get("decals", []):
        if d["image"] not in ids:  # rejected by moderation
            continue
        pos, nrm = to_studio(d["position"]), to_studio(d["normal"])
        up = "Vector3.zAxis" if abs(nrm[1]) > 0.99 else "Vector3.yAxis"
        decal_lines.append(
            "\t{ name = %s, image = %s, pos = %s, normal = %s, up = %s, w = %s, h = %s, opacity = %s }" % (
                _s(d["name"]), _s(ids[d["image"]]), _vec(pos), _vec(nrm), up,
                _n(d["size"][0] * STUDS_PER_UNIT), _n(d["size"][1] * STUDS_PER_UNIT),
                _n(d["opacity"])))

    lo, hi = to_studio(manifest["bounds"]["min"]), to_studio(manifest["bounds"]["max"])
    # to_studio can flip an axis, so re-sort per axis
    mn = [min(a, b) for a, b in zip(lo, hi)]
    mx = [max(a, b) for a, b in zip(lo, hi)]
    pivot = [(mn[0] + mx[0]) / 2, mn[1], (mn[2] + mx[2]) / 2]

    return """-- Generated by rbxasset deliver. Assembles %(label)s in Studio.
local InsertService = game:GetService("InsertService")
local Selection = game:GetService("Selection")

local MODEL_ID = %(model_id)s
local MESHES = {
%(meshes)s
}
local DECALS = {
%(decals)s
}

local function loadAsset(id)
	return InsertService:LoadAsset(tonumber(id))
end

-- Map assets are Decal assets; resolve each to its image once.
local imageCache = {}
local function image(id)
	if not imageCache[id] then
		local container = loadAsset(id)
		local decal = container:FindFirstChildWhichIsA("Decal", true)
		if not decal then
			error("asset " .. id .. " has no Decal inside")
		end
		imageCache[id] = decal.Texture
		container:Destroy()
	end
	return imageCache[id]
end

local container = loadAsset(MODEL_ID)
local model = container:FindFirstChildWhichIsA("Model")
if not model then
	error("asset " .. MODEL_ID .. " contains no Model")
end
model.Parent = nil
container:Destroy()

local missing = {}
for _, spec in ipairs(MESHES) do
	local part = model:FindFirstChild(spec.name, true)
	if not (part and part:IsA("MeshPart")) then
		table.insert(missing, spec.name)
	end
end
if #missing > 0 then
	error("missing meshes in loaded model: " .. table.concat(missing, ", "))
end

for _, spec in ipairs(MESHES) do
	local part = model:FindFirstChild(spec.name, true)
	part.Anchored = true
	part.CanCollide = spec.collide
	local sa = Instance.new("SurfaceAppearance")
	sa.ColorMap = image(spec.color)
	sa.NormalMap = image(spec.normal)
	sa.RoughnessMap = image(spec.roughness)
	if spec.metalness then
		sa.MetalnessMap = image(spec.metalness)
	end
	sa.Parent = part
end

for _, spec in ipairs(DECALS) do
	local p = Instance.new("Part")
	p.Name = spec.name
	p.Anchored = true
	p.CanCollide = false
	p.Transparency = 1
	p.Size = Vector3.new(spec.w, spec.h, %(thick)s)
	p.CFrame = CFrame.lookAt(spec.pos, spec.pos + spec.normal, spec.up)
	local d = Instance.new("Decal")
	d.Face = Enum.NormalId.Front
	d.Texture = image(spec.image)
	d.Transparency = 1 - spec.opacity
	d.Parent = p
	p.Parent = model
end

model.Name = %(name)s
model.WorldPivot = CFrame.new(%(pivot)s)
model.Parent = workspace
Selection:Set({ model })
print(%(name)s .. ": " .. #MESHES .. " meshes, " .. #DECALS .. " decals")
""" % {
        "label": _s(asset_name).replace("\n", " "),
        "model_id": _s(model_id),
        "meshes": ",\n".join(mesh_lines) + ",",
        "decals": (",\n".join(decal_lines) + ",") if decal_lines else "",
        "thick": _n(DECAL_THICKNESS),
        "name": _s(asset_name),
        "pivot": ", ".join(_n(x) for x in pivot),
    }
